_BY_ID = {lane["id"]: lane for lane in LANES}


def ids() -> list[str]:
    """Every lane id, in catalog order."""
    return [lane["id"] for lane in LANES]


def by_id(lane_id: str):
    """Exact lane lookup, or None. Case/space tolerant on the id."""
    if not lane_id:
        return None
    key = str(lane_id).strip().lower().replace(" ", "-").replace("_", "-")
    return _BY_ID.get(key)


def families() -> dict[str, int]:
    """family -> lane count."""
    out: dict[str, int] = {}
    for lane in LANES:
        out[lane["family"]] = out.get(lane["family"], 0) + 1
    return out


def search(query: str, limit: int = 8) -> list[dict]:
    """Substring search over id, name, family, vibe, style and tempo."""
    if not query:
        return list(LANES[:limit])
    q = str(query).strip().lower()
    scored: list[tuple[int, dict]] = []
    for lane in LANES:
        hay = " ".join([
            lane["id"], lane["name"], lane["family"], lane["vibe"],
            lane["style"], lane["bpm"], " ".join(lane["tags"]),
        ]).lower()
        if q in lane["id"] or q in lane["name"].lower():
            scored.append((0, lane))
        elif q in hay:
            scored.append((1, lane))
    scored.sort(key=lambda pair: (pair[0], pair[1]["bpm_mid"]))
    return [lane for _score, lane in scored[:limit]]
